USE ai_disaster_response;

-- ============================================================
-- PHASE 8 SCHEMA ENHANCEMENT: ALERTS & DAMAGE REPORTS
-- ============================================================

-- 1. INCIDENT ↔ ALERT JUNCTION TABLE
CREATE TABLE IF NOT EXISTS incident_alert (
    INCIDENT_ALERT_ID INT NOT NULL,
    INCIDENT_ID INT NOT NULL,
    ALERT_ID INT NOT NULL,
    PRIMARY KEY (INCIDENT_ALERT_ID),
    KEY FK_INCIDENT_ALERT_INCIDENT (INCIDENT_ID),
    KEY FK_INCIDENT_ALERT_ALERT (ALERT_ID),
    CONSTRAINT FK_INCIDENT_ALERT_INCIDENT
        FOREIGN KEY (INCIDENT_ID)
        REFERENCES incident(INCIDENT_ID),
    CONSTRAINT FK_INCIDENT_ALERT_ALERT
        FOREIGN KEY (ALERT_ID)
        REFERENCES alert(ALERT_ID)
);

-- 2. ALERT ACKNOWLEDGEMENT TABLE (multi-user independent acknowledgement)
CREATE TABLE IF NOT EXISTS alert_acknowledgement (
    ACKNOWLEDGEMENT_ID INT NOT NULL,
    ALERT_ID INT NOT NULL,
    USER_ID INT NOT NULL,
    ACKNOWLEDGED_TIME DATETIME,
    PRIMARY KEY (ACKNOWLEDGEMENT_ID),
    KEY FK_ALERT_ACK_ALERT (ALERT_ID),
    KEY FK_ALERT_ACK_USER (USER_ID),
    CONSTRAINT FK_ALERT_ACK_ALERT
        FOREIGN KEY (ALERT_ID)
        REFERENCES alert(ALERT_ID),
    CONSTRAINT FK_ALERT_ACK_USER
        FOREIGN KEY (USER_ID)
        REFERENCES user(USER_ID)
);

-- 3. INCIDENT ↔ DAMAGE REPORT JUNCTION TABLE
CREATE TABLE IF NOT EXISTS incident_damage_report (
    INCIDENT_DAMAGE_ID INT NOT NULL,
    INCIDENT_ID INT NOT NULL,
    REPORT_ID INT NOT NULL,
    PRIMARY KEY (INCIDENT_DAMAGE_ID),
    KEY FK_DAMAGE_INCIDENT (INCIDENT_ID),
    KEY FK_DAMAGE_REPORT (REPORT_ID),
    CONSTRAINT FK_DAMAGE_INCIDENT
        FOREIGN KEY (INCIDENT_ID)
        REFERENCES incident(INCIDENT_ID),
    CONSTRAINT FK_DAMAGE_REPORT
        FOREIGN KEY (REPORT_ID)
        REFERENCES damage_report(REPORT_ID)
);
