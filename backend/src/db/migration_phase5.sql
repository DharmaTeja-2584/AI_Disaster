USE ai_disaster_response;

-- ============================================================
-- PHASE 5 SCHEMA ENHANCEMENT (OPTION 2: JUNCTION TABLE)
-- ============================================================

-- 1. Add coordinate columns to RESPONSE_TEAM
ALTER TABLE RESPONSE_TEAM
ADD COLUMN LATITUDE DECIMAL(10,6),
ADD COLUMN LONGITUDE DECIMAL(10,6);

-- 2. Create N:M INCIDENT ↔ RESPONSE_TEAM junction table
CREATE TABLE IF NOT EXISTS INCIDENT_DISPATCH (
    DISPATCH_ID INTEGER PRIMARY KEY,
    INCIDENT_ID INTEGER NOT NULL,
    TEAM_ID INTEGER NOT NULL,
    DISPATCH_TIME DATETIME,
    STATUS VARCHAR(20),

    CONSTRAINT FK_DISPATCH_INCIDENT
        FOREIGN KEY (INCIDENT_ID)
        REFERENCES INCIDENT(INCIDENT_ID),

    CONSTRAINT FK_DISPATCH_TEAM
        FOREIGN KEY (TEAM_ID)
        REFERENCES RESPONSE_TEAM(TEAM_ID)
);
